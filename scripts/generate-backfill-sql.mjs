#!/usr/bin/env node
// One-time backfill generator (admin-panel pivot, task #27): turns the
// existing approved CSVs in data/ into a SQL script that inserts them
// as `products` rows, so the live site doesn't go blank the moment the
// public pages switch from the static bundle to reading migration
// 0005's tables. Run this locally (`node scripts/generate-backfill-sql.mjs`)
// and apply the resulting supabase/migrations/0006_backfill_catalogue.sql
// via the Supabase SQL Editor, same manual workflow as 0001-0005,
// *after* 0005 has been applied. Idempotent (ON CONFLICT DO NOTHING on
// the unique slug), so it's safe to re-run.
//
// Slugs are generated with the exact same algorithm as
// generate-catalogue.mjs so existing /collection/<slug> and
// /atelier-supply/<slug> URLs keep working unchanged.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { parse } from "csv-parse/sync";

const rootDir = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const dataDir = path.join(rootDir, "data");
const outPath = path.join(rootDir, "supabase", "migrations", "0006_backfill_catalogue.sql");

function slugify(input) {
  return input
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function uniqueSlug(base, seen) {
  let slug = base || "item";
  while (seen.has(slug)) slug += "-x";
  seen.add(slug);
  return slug;
}

// SQL string literal escaping: doubles embedded single quotes.
function sqlString(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}
function sqlStringOrNull(value) {
  return value ? sqlString(value) : "null";
}

const perfumeRows = parse(readFileSync(path.join(dataDir, "perfumes.csv"), "utf-8"), {
  columns: true,
  skip_empty_lines: true,
  trim: true,
});
const supplyRows = parse(readFileSync(path.join(dataDir, "atelier-supply.csv"), "utf-8"), {
  columns: true,
  skip_empty_lines: true,
  trim: true,
});

const lines = [];
lines.push(
  "-- One-time backfill of the pre-admin-panel static catalogue into the",
  "-- products table (migration 0005), generated by",
  "-- scripts/generate-backfill-sql.mjs from data/perfumes.csv and",
  "-- data/atelier-supply.csv. Apply after 0005. Idempotent: re-running is",
  "-- safe, existing slugs are left untouched.",
  "--",
  "-- Legacy rows have no perfume_type / product_type_id / mood set (those",
  "-- CSVs never carried that data) -- an admin should fill them in via",
  "-- the edit form when convenient; the public site already tolerates a",
  "-- null Type gracefully (falls back to \"Perfume Oil\" / \"Fragrance",
  "-- Material\" display text).",
  "",
);

const perfumeSlugs = new Set();
for (const row of perfumeRows) {
  const slug = uniqueSlug(slugify(row.name), perfumeSlugs);
  const tags = (row.scent_profile || "")
    .split("|")
    .map((s) => s.trim())
    .filter(Boolean);
  const price = row.price ? Number(row.price) : 0;
  const mood = row.mood?.trim() || null;

  lines.push(
    `insert into products (category, slug, name, description, price, currency, size, status, mood)`,
    `values ('aurielle_collection', ${sqlString(slug)}, ${sqlString(row.name)}, ${sqlStringOrNull(row.description)}, ${price}, ${sqlString(row.currency || "₱")}, ${sqlStringOrNull(row.size)}, 'active', ${sqlStringOrNull(mood)})`,
    `on conflict (slug) do nothing;`,
  );

  if (tags.length > 0) {
    const tagList = tags.map((t) => sqlString(t)).join(", ");
    lines.push(
      `insert into product_tags (product_id, tag)`,
      `select p.id, t.tag from products p, unnest(array[${tagList}]) as t(tag)`,
      `where p.slug = ${sqlString(slug)}`,
      `on conflict (product_id, tag) do nothing;`,
    );
  }
  lines.push("");
}

const supplySlugs = new Set();
for (const row of supplyRows) {
  const serialNumber = Number(row.serial_number);
  const slug = uniqueSlug(`${slugify(row.name)}-${String(serialNumber).padStart(3, "0")}`, supplySlugs);
  const price = Number(row.price);

  lines.push(
    `insert into products (category, slug, name, description, price, currency, size, status, serial_number)`,
    `values ('atelier_supply', ${sqlString(slug)}, ${sqlString(row.name)}, ${sqlStringOrNull(row.description)}, ${price}, ${sqlString(row.currency || "USD")}, ${sqlStringOrNull(row.unit || "KG")}, 'active', ${serialNumber})`,
    `on conflict (slug) do nothing;`,
    "",
  );
}

writeFileSync(outPath, lines.join("\n") + "\n");
console.log(
  `✓ generate-backfill-sql: wrote ${perfumeRows.length} perfumes, ${supplyRows.length} supply materials to ${path.relative(rootDir, outPath)}`,
);
